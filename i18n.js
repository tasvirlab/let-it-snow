// 'auto' → the OS language if it's Russian or Uzbek, otherwise English
function resolve(lang, app) {
  if (dict[lang]) return lang;
  const l = ((app.getPreferredSystemLanguages?.() || [])[0] || app.getLocale() || 'en').toLowerCase();
  return l.startsWith('ru') ? 'ru' : l.startsWith('uz') ? 'uz' : 'en';
}

